import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const output = new URL('../docker/runtime/rss-transport.mjs', import.meta.url);
const result = await build({
  configFile: false,
  logLevel: 'error',
  build: {
    target: 'node22',
    ssr: fileURLToPath(new URL('./rss-transport-main.ts', import.meta.url)),
    write: false,
    minify: false,
    rolldownOptions: { output: { format: 'es', codeSplitting: false } },
  },
});
if (
  Array.isArray(result) ||
  !('output' in result) ||
  result.output.length !== 1 ||
  result.output[0].type !== 'chunk'
) {
  throw new Error('Expected one standalone RSS transport module');
}
const generated =
  '// Generated by scripts/build-rss-transport.mjs. Edit scripts/rss-transport-*.ts or shared RSS policy.\n' +
  result.output[0].code;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8').catch(() => '')) !== generated) {
    console.error('RSS transport artifact is stale. Run node scripts/build-rss-transport.mjs.');
    process.exitCode = 1;
  }
} else {
  await mkdir(new URL('.', output), { recursive: true });
  await writeFile(output, generated);
}
